// Release signing comes from environment variables (set by the GitHub workflow
// from repository secrets). Without them the release APK is signed with the
// debug key so it still installs.
val keystoreFile = System.getenv("ANDROID_KEYSTORE_FILE")
val hasReleaseKey = !keystoreFile.isNullOrBlank() && file(keystoreFile).exists()

